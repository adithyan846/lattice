#!/usr/bin/env python3
"""Generate a Markdown tree of the repository for docs/file-tree.md."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

DEFAULT_EXCLUDES = {
    ".git",
    ".github/workflows/__pycache__",
    "__pycache__",
    "build",
    ".cache",
    ".pytest_cache",
}


def excluded(path: Path, root: Path, extra: set[str]) -> bool:
    relative = path.relative_to(root).as_posix()

    if relative in extra:
        return True

    return any(part in DEFAULT_EXCLUDES for part in path.relative_to(root).parts)


def build_tree(directory: Path, root: Path, prefix: str, extra: set[str]) -> list[str]:
    entries = sorted(
        (entry for entry in directory.iterdir() if not excluded(entry, root, extra)),
        key=lambda entry: (entry.is_file(), entry.name.lower()),
    )
    lines: list[str] = []

    for index, entry in enumerate(entries):
        last = index == len(entries) - 1
        connector = "└── " if last else "├── "
        suffix = "/" if entry.is_dir() else ""
        lines.append(f"{prefix}{connector}{entry.name}{suffix}")

        if entry.is_dir():
            extension = "    " if last else "│   "
            lines.extend(build_tree(entry, root, prefix + extension, extra))

    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="repository root (default: .)")
    parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        help="additional path to exclude, relative to the root (repeatable)",
    )
    args = parser.parse_args()

    root = Path(args.root).resolve()
    extra = set(args.exclude)
    lines = build_tree(root, root, "", extra)

    files = sum(1 for line in lines if not line.rstrip().endswith("/"))
    directories = len(lines) - files

    print("# File tree")
    print()
    print("Generated by `make tree` (`tools/gen_tree.py`). Do not edit by hand.")
    print()
    print(f"{root.name}/")
    print("\n".join(lines))
    print()
    print(f"{directories} directories, {files} files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
