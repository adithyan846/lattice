#!/usr/bin/env python3
"""Generate C structs from the simple uORB-style .msg files in src/msg.

Supported syntax:

    uint64 timestamp
    float32[4] q
    float32 x
    bool valid
    char[50] text

This is intentionally a small subset of PX4's uORB message language. It is
enough for the scaffold and easy to audit. If the project later adopts the
real uORB generator, replace this script and keep the .msg files as the source
of truth.

Usage:
    python3 tools/msg_gen.py --input src/msg --output src/msg/generated
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TYPE_MAP = {
    "uint64": "uint64_t",
    "uint32": "uint32_t",
    "uint16": "uint16_t",
    "uint8": "uint8_t",
    "int64": "int64_t",
    "int32": "int32_t",
    "int16": "int16_t",
    "int8": "int8_t",
    "float32": "float",
    "float64": "double",
    "bool": "bool",
    "char": "char",
}

ARRAY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)(?:\[(\d+)\])?$")


class MessageField:
    def __init__(self, c_type: str, name: str, array_len: int | None):
        self.c_type = c_type
        self.name = name
        self.array_len = array_len

    def declaration(self) -> str:
        if self.array_len is None:
            return f"    {self.c_type} {self.name};"
        return f"    {self.c_type} {self.name}[{self.array_len}];"


class Message:
    def __init__(self, name: str, path: Path, fields: list[MessageField]):
        self.name = name
        self.path = path
        self.fields = fields


def parse_message(path: Path) -> Message:
    fields: list[MessageField] = []
    seen: set[str] = set()

    for line_number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw_line.split("#", 1)[0].strip()

        if not line:
            continue

        parts = line.split()
        if len(parts) != 2:
            raise ValueError(f"{path}:{line_number}: expected 'type name', got {raw_line!r}")

        type_token, name = parts
        match = ARRAY_RE.match(type_token)
        if not match:
            raise ValueError(f"{path}:{line_number}: invalid type {type_token!r}")

        base_type, array_len_text = match.groups()
        array_len = int(array_len_text) if array_len_text else None

        # Also accept the C-style "float32 q[4]" form.
        name_match = ARRAY_RE.match(name)
        if name_match and name_match.group(2):
            if array_len is not None:
                raise ValueError(f"{path}:{line_number}: array length specified twice")
            name = name_match.group(1)
            array_len = int(name_match.group(2))

        if base_type not in TYPE_MAP:
            raise ValueError(f"{path}:{line_number}: unsupported type {base_type!r}")

        if name in seen:
            raise ValueError(f"{path}:{line_number}: duplicate field {name!r}")

        seen.add(name)
        fields.append(MessageField(TYPE_MAP[base_type], name, array_len))

    if not fields:
        raise ValueError(f"{path}: message has no fields")

    if fields[0].name != "timestamp":
        raise ValueError(f"{path}: first field must be 'uint64 timestamp'")

    return Message(path.stem, path, fields)


def generate_header(messages: list[Message]) -> str:
    lines = [
        "/* Auto-generated by tools/msg_gen.py. Do not edit by hand. */",
        "#ifndef UORB_TOPICS_H",
        "#define UORB_TOPICS_H",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "#pragma pack(push, 1)",
        "",
    ]

    for message in messages:
        lines.append(f"/* {message.name} */")
        lines.append("typedef struct {")

        for field in message.fields:
            lines.append(field.declaration())

        lines.append(f"}} {message.name}_s;")
        lines.append("")

    lines.extend([
        "#pragma pack(pop)",
        "",
        "#endif /* UORB_TOPICS_H */",
        "",
    ])

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate uORB C headers from .msg files")
    parser.add_argument("--input", default="src/msg", help="directory containing .msg files")
    parser.add_argument("--output", default="src/msg/generated", help="output directory")
    args = parser.parse_args()

    input_dir = Path(args.input)
    output_dir = Path(args.output)

    if not input_dir.is_dir():
        print(f"error: input directory not found: {input_dir}", file=sys.stderr)
        return 1

    paths = sorted(input_dir.glob("*.msg"))
    if not paths:
        print(f"error: no .msg files in {input_dir}", file=sys.stderr)
        return 1

    try:
        messages = [parse_message(path) for path in paths]
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    names = [message.name for message in messages]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        print(f"error: duplicate message names: {duplicates}", file=sys.stderr)
        return 1

    output_dir.mkdir(parents=True, exist_ok=True)
    header_path = output_dir / "uorb_topics.h"
    header_path.write_text(generate_header(messages), encoding="utf-8")

    print(f"generated {header_path} ({len(messages)} messages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
